// ═══════════════════════════════════════════════════════════════════════════════
// PROCUREMENT OPEN-FORMAT ROBOT STYLES — how a simulated student decides WHEN TO STOP.
//
// ⚠⚠ THE SEALED PERSONAS DO NOT PORT, AND THIS IS NOT LAZINESS ABOUT REUSE. The six in
// `procurement-styles.mjs` vary by MARKUP RELATIVE TO β, and the open format has no
// markup: there is no single bid to mark up, and β is the sealed first-price equilibrium,
// which judges nothing that happens in a descending auction. Concretely:
//
//   • `cost-bidder` and `equilibrium` COLLAPSE INTO ONE BEHAVIOUR here — undercutting
//     while the price is above your cost and stopping at it IS the dominant strategy
//     (§1), so "bid your cost" and "play the equilibrium" are the same robot.
//   • `under-marker` has no analogue AT ALL: the only way to be more aggressive than
//     optimal is to bid below cost, and no bidder may now do that.
//
// So the open cohort is defined by EXIT THRESHOLD instead, which is the quantity the
// Tier-3 scatter actually plots (§7). THREE styles, named for what they do:
//
//   exits at cost      threshold = cost            → ON the 45° line: the benchmark
//   exits early        threshold = cost + 8..15    → ABOVE it: money left on the table
//   random exit        threshold = cost + 0..20    → the noise a real class contains
//
// ⚠⚠ THERE WAS A FOURTH — `exits below cost` — AND IT IS DELETED, NOT LEFT DEAD (Elena,
// 2026-08-04). It stopped 3–8 BELOW its own cost to populate the region under the 45°
// line by winning at a loss. **No bidder may bid below their own cost any more**, in
// either format: the machine refuses the bid and auto-drops a player the price has passed.
// That region cannot be populated by anybody, so a persona whose only job was to populate
// it would produce a cohort of refused clicks rather than a chart.
//
// ⚠⚠ THE GOAL IS SPREAD IN EXIT PRICES. A cohort that all exited at cost would produce a
// single dot on the 45° line and prove nothing about the chart. Elena points at this
// chart in lecture and names what she is looking at, so the thing she points at has to
// have been generated by the rule she is naming.
//
// ⚠⚠ THE TRIGGER IS `minimum next bid >= threshold`, NEVER `price >= threshold`. At a
// standing of 48 with a cost of 47 the PRICE is still above cost, but the next legal bid
// is 46 — already a loss. A robot that waited for the price to fall below its threshold
// would sit there forever and THE ROUND WOULD NEVER RESOLVE, which is precisely why the
// open cohort produced no exit prices before this file existed. The threshold is compared
// against the number the screen calls "Minimum next bid".
//
// ⚠ EVERY STYLE DECIDES FROM WHAT IS ON THE STUDENT'S OWN SCREEN — their own cost, and
// the minimum next bid. NOTHING here reads a rival's cost, and nothing can: the server
// does not send one during play (§4). A robot handed the bots' costs would make the
// cohort's chart say something false about what a student can achieve.
// ═══════════════════════════════════════════════════════════════════════════════

/** A small deterministic wobble, keyed on the robot and the round rather than on
 *  `Math.random`, so a dry run is reproducible and a failure can be re-run. Copied from
 *  `procurement-styles.mjs` deliberately: the two cohorts are independent, and a shared
 *  helper would mean a change made for one silently reshaped the other's chart. */
function jitter(key) {
  let h = 2166136261
  for (let i = 0; i < key.length; i++) { h ^= key.charCodeAt(i); h = Math.imul(h, 16777619) }
  return ((h >>> 0) % 1000) / 1000
}

/** Spread `lo..hi` deterministically from a key. */
const band = (key, lo, hi) => lo + jitter(key) * (hi - lo)

/**
 * ⚠ THE LABELS ARE WHAT APPEARS IN ELENA'S REPORTS, so they are written to be read by
 * somebody looking at a scatter rather than at this file: each says what the robot DID,
 * not how it was parameterised.
 */
export const OPEN_STYLES = [
  {
    name: 'exits at cost',
    note: 'stops exactly at its own cost — the benchmark, sitting ON the 45° line',
    threshold: (cost) => cost,
  },
  {
    name: 'exits early',
    note: 'stops 8–15 above cost — leaves money on the table, the band ABOVE the line',
    threshold: (cost, key) => cost + Math.round(band(key, 8, 15)),
  },
  {
    name: 'random exit',
    note: 'no policy at all — stops anywhere from cost to cost + 20',
    threshold: (cost, key) => cost + Math.round(band(key, 0, 20)),
  },
]

/** ⚠ THE LABELS, as one list, for anything that needs to name them without importing the
 *  behaviour — reports, docs, the launcher's own logging. */
export const OPEN_STYLE_NAMES = OPEN_STYLES.map(s => s.name)

/**
 * Deal styles round-robin across a cohort.
 *
 * ⚠ ROUND-ROBIN, NOT RANDOM. With three styles and eight seats a random deal leaves one
 * unrepresented often enough to matter, and the chart it is meant to demonstrate then
 * quietly lacks one of its features — on the run somebody is watching.
 */
export function assignOpenStyles(count) {
  return Array.from({ length: Math.max(0, count | 0) },
    (_, i) => OPEN_STYLES[i % OPEN_STYLES.length])
}

/**
 * The decision, in one place: given what the screen shows, bid the minimum or drop out.
 *
 * @param minNextBid  the screen's "Minimum next bid" — ⚠ NOT the standing price
 * @param cost        the student's own drawn cost, from their own screen
 * @returns 'bid' | 'dropOut'
 */
export function openDecision(style, { minNextBid, cost, key }) {
  if (minNextBid === null || !Number.isFinite(minNextBid)) return 'dropOut'
  return minNextBid >= style.threshold(cost, key) ? 'bid' : 'dropOut'
}
